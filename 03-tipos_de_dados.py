#Python é uma linguagem tipada, tem diferentes tipos de dados, e cada tipo de dado tem suas próprias características e comportamentos.
#Python é uma linguagem de tipagem dinâmica, ou seja, não precisamos declarar o tipo da variável, o Python faz isso automaticamente.

#String (str): é uma sequência de caracteres, ou seja, um texto. É representado por aspas simples ou duplas.
#Exemplo:
nome = "Iago"

#Integer (int): é um número inteiro, ou seja, sem casas decimais. É representado por números sem ponto.
#Exemplo:
idade = 24

#Float (float): é um número racional, ou seja, pode ter casas decimais. É representado por números com ponto, não vírgula.
#Exemplo:
altura = 1.85

#Boolean (bool): é um valor lógico, só de duas possibilidades. É representado por True ou False(sempre com letra maiúscula).
#Exemplo:
logica = True
logica2 = False